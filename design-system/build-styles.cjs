/* Build-time only. No browser code, Google access or runtime dependencies. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const postcss=require(process.env.PERCU_POSTCSS_PATH||'postcss');
const root=path.resolve(__dirname,'..');
const lf=s=>s.replace(/\r\n/g,'\n');
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const targets={'design-system/app.css':'design-system/app-entry.css','design-system/repertoire-bundle.css':'design-system/repertoire-entry.css','design-system/course-bundle.css':'design-system/group-courses.css'};
const inputs={};
function flatten(file,chain=[]){
 const full=path.resolve(root,file);
 if(!full.startsWith(root+path.sep)||chain.includes(full))throw Error('Invalid or circular CSS import: '+file);
 const source=lf(fs.readFileSync(full,'utf8'));inputs[path.relative(root,full).split(path.sep).join('/')]=hash(source);
 const ast=postcss.parse(source,{from:full});
 for(const node of [...ast.nodes])if(node.type==='atrule'&&node.name.toLowerCase()==='import'){
  const match=node.params.match(/^url\(["']([^"']+)["']\)$/);
  if(!match||/^[a-z]+:|^\/\//i.test(match[1]))throw Error('Only local, unconditional CSS imports are allowed: '+node.params);
  const imported=path.relative(root,path.resolve(path.dirname(full),match[1]));
  node.replaceWith(...flatten(imported,[...chain,full]).nodes);
 }
 return ast;
}
function scope(rule){
 const names=[];let node=rule.parent;
 while(node.type!=='root'){
  if(node.type!=='atrule'||!['media','supports'].includes(node.name.toLowerCase()))return null;
  names.unshift(node.name+' '+node.params.trim());node=node.parent;
 }
 return names.join(' > ');
}
function clean(ast){
 const declarations=[];ast.walkDecls(d=>declarations.push(d));const seen=new Set();let removed=0;
 for(const d of declarations.reverse()){
  if(d.parent.type!=='rule')continue;
  const context=scope(d.parent);if(context===null)continue;
  const property=d.prop.startsWith('--')?d.prop:d.prop.toLowerCase();
  const key=JSON.stringify([context,d.parent.selector,property,d.value,!!d.important]);
  // Identical selector, condition, value and importance only; keep different-value fallbacks.
  if(seen.has(key)){d.remove();removed++;}else seen.add(key);
 }
 ast.walkRules(r=>{if(!r.nodes.some(n=>n.type!=='comment'))r.remove();});
 ast.walkAtRules(a=>{if(['media','supports'].includes(a.name)&&a.nodes&&!a.nodes.some(n=>n.type!=='comment'))a.remove();});
 return {inputDeclarations:declarations.length,removedDeclarations:removed};
}
const outputs={};
for(const [destination,entry]of Object.entries(targets)){
 const ast=flatten(entry),before=ast.toString(),counts=clean(ast);
 const css='/* Generated by design-system/build-styles.cjs; edit the entry sources. */\n'+ast.toString().replace(/[ \t]+$/gm,'').trimEnd()+'\n';
 const file=path.join(root,destination);
 if(process.argv.includes('--check')){if(lf(fs.readFileSync(file,'utf8'))!==css)throw Error('Stale CSS: '+destination);}
 else fs.writeFileSync(file,css);
 outputs[destination]={entry,sha256:hash(css),inputBytes:Buffer.byteLength(before),outputBytes:Buffer.byteLength(css),...counts};
}
inputs['design-system/build-styles.cjs']=hash(lf(fs.readFileSync(__filename,'utf8')));
const manifest={schema:1,inputs,outputs};
const result=JSON.stringify(manifest,null,2)+'\n',file=path.join(__dirname,'build-manifest.json');
if(process.argv.includes('--check')){if(lf(fs.readFileSync(file,'utf8'))!==result)throw Error('Stale style manifest');}
else fs.writeFileSync(file,result);
console.log(JSON.stringify({outputs},null,2));
